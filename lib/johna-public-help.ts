/**
 * Customer-safe Johna-S help. Only common user workflows are answered
 * automatically. Never feed administrator docs, repo code, database contents,
 * settings, conversations or organization records to a generative model.
 */
const confidential=/(?:كيف\s*(?:تم|اتعمل|بني|تطوير|انشاء|إنشاء)\s*(?:النظام|الموقع|المنصه|البرنامج)|بنيه\s*(?:النظام|المنصه)|الكود|شفرة|سورس|source\s*code|github|مستودع|database|قاعده\s*البيانات|supabase|vercel|api|endpoint|token|مفتاح|سري|كلمه\s*المرور|صلاحيات|super.?admin|مدير\s*عام|لوحه\s*المدير|اداره\s*المؤسسات|المستاجرين|المنظمات|سجل\s*التدقيق|الحمايه|امن\s*النظام|بنيه\s*الخادم|server|backend|frontend|architecture|development|technolog|framework|react|vue|بيانات\s*العملاء|ارباح\s*الشركه|معلومات\s*خاصه|معلومات\s*حساسه)/i;
const normalize=(s:string)=>s.toLocaleLowerCase("ar").normalize("NFKC")
  .replace(/[\u064B-\u065F\u0670]/g,"")
  .replace(/[أإآ]/g,"ا").replace(/ى/g,"ي").replace(/ة/g,"ه").trim();

export function johnaPublicAnswer(question:string):string|null{
 const q=normalize(question);
 // Sensitive or implementation-oriented questions always go to staff,
 // even when they happen to also contain common navigation words.
 if(confidential.test(q))return null;
 if(/^(?:السلام عليكم|وعليكم السلام|سلام|اهلا|اهلين|مرحبا|صباح الخير|مساء الخير|hello|hi)[؟?!.\s]*$/i.test(q))
  return "أهلًا بك في خدمة عملاء Johna-S. أقدر أساعدك في استخدام وظائف النظام اليومية. ما العملية التي تريد تنفيذها؟";
 if(/^(?:شكرا|شكراً|متشكر|تسلم|thanks|thank you)[؟?!.\s]*$/i.test(q))
  return "العفو، هل تحتاج مساعدة في أي خطوة أخرى؟";
 // A punctuation-only / emoji-only message is not a human-handoff request.
 // Ask for clarification and preserve this conversation's AI mode. Never
 // invent a business answer or send the raw message to a model.
 if((q.match(/\p{L}/gu)||[]).length<3)
  return "من فضلك اكتب سؤالك أو صف العملية التي تحتاج المساعدة فيها، مثل البيع أو المنتجات أو المخزون. سأساعدك بالمعلومات المتاحة.";

 if(/(?:نقطه\s*البيع|pos|عمليه\s*بيع|تسجيل\s*بيع|عمل\s*فاتوره\s*بيع|البيع\s*فين|ازاي\s*ابيع)/i.test(q))
  return "افتح «نقطة البيع» من القائمة الجانبية، وتأكد من الفرع، ثم اختر الأصناف والكميات. راجع الطلب قبل الدفع، وتحقق من تسجيله قبل إعادة المحاولة.";
 if(/(?:اضافه\s*منتج|اضيف\s*منتج|انشاء\s*منتج|المنتجات|الاصناف|صنف\s*جديد)/i.test(q))
  return "افتح «المنتجات» من القائمة الجانبية. اختر إضافة منتج إن ظهر لك الخيار، وأدخل بياناته بالفرع الصحيح، ثم راجعها قبل الحفظ. إذا لم يظهر الزر، تواصل مع مسؤولك.";
 if(/(?:المخزون|رصيد\s*خامات|الكميات\s*المتاحه|المستودعات|المخازن)/i.test(q))
  return "افتح «مركز المخزون» من القائمة الجانبية، ثم راجع المخزون أو المستودعات. تأكد من الفرع والمخزن ووحدة القياس قبل مقارنة الأرصدة، ولا تُجرِ تسوية بلا اعتماد.";
 if(/(?:تحويل\s*مخزني|تحويل\s*بين|نقل\s*خامه|التحويلات)/i.test(q))
  return "افتح «التحويلات» من قسم المخزون، وحدد المصدر والوجهة والخامة والكمية. راجع المعاينة والأرصدة قبل الحفظ والاعتماد، وتحقق من سجل التحويل قبل تكرار العملية.";
 if(/(?:جرد|تسويه\s*مخزون|عد\s*الخامات)/i.test(q))
  return "افتح شاشة «الجرد والتسويات»، وحدد الفرع والمخزن ثم أدخل الكميات الفعلية واحفظ المسودة. راجع الفروق مع المسؤول المختص قبل اعتماد أي تغيير.";
 if(/(?:المشتريات|فاتوره\s*شراء|الموردين|طلب\s*شراء|استلام\s*مشتريات)/i.test(q))
  return "افتح «مركز المشتريات» من القائمة الجانبية، ثم اختر الفواتير أو طلبات الشراء أو الاستلام حسب المطلوب. راجع المورد والفرع والمخزن والكميات وحالة المستند قبل الحفظ.";
 if(/(?:التسعير|سعر\s*بيع|تغيير\s*السعر|سعر\s*المنتج)/i.test(q))
  return "افتح «التسعير»، ثم اختر المنتجات وابحث عن الصنف. راجع الفرع والتكلفة وسعر البيع قبل الحفظ. التعديل يتطلب الصلاحية المناسبة.";
 if(/(?:الوردية|الورديه|الشفت|الشيفت|اغلاق\s*اليوم)/i.test(q))
  return "افتح «الشفتات» لمراجعة الوردية والتقارير. قبل الإغلاق، راجع العمليات المفتوحة والنقدية الفعلية. إغلاق الوردية يختلف عن إغلاق اليوم المالي.";
 if(/(?:تقارير|تقرير\s*مبيعات|تقرير\s*يومي|المبيعات\s*فين)/i.test(q))
  return "افتح «التقارير» من القائمة الجانبية، ثم اختر التقرير والفترة والفرع واضغط عرض إن كان متاحًا. بعض التقارير تظهر فقط للمستخدم المخوّل.";
 if(/(?:طباعه|طباعه\s*فاتوره|طابعه|الايصال|الفاتوره\s*مش\s*بتطبع)/i.test(q))
  return "تأكد من تشغيل الطابعة واتصالها، واختيار الطابعة المناسبة للفرع، ثم جرّب وظيفة الطباعة من الشاشة. لا تُكرر عملية الدفع إذا فشلت الطباعة فقط.";
 if(/(?:مش\s*شغال|خطا|تعذر|مش\s*بيفتح|مش\s*ظاهر|مشكله)/i.test(q))
  return "اذكر اسم الشاشة ورسالة الخطأ كما ظهرت لك، دون كلمات مرور أو بيانات مالية خاصة. إذا كانت العملية بيعًا أو دفعًا، راجع سجلها قبل إعادة المحاولة.";
 return null;
}
