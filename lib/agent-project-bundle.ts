/** Portable, dependency-free ZIP packaging for owned AGENT Work experiments.
 * Generated program files are detached from the AGENT source repository.
 * Producing a ZIP never writes or merges anything into GitHub.
 */
export type PortableExperiment={
  id:string;task:string;code:string;steps:string[];
  status:string;sandbox_ran:boolean;sandbox_succeeded:boolean|null;
  execution_log:string|null;github_run_id:number|null;
};
function zipStore(entries:readonly {name:string;content:string}[]):Uint8Array{
  if(entries.length===0||entries.length>12)throw new Error("INVALID_PROJECT_FILES");
  const te=new TextEncoder();
  const parts:Uint8Array[]=[],central:Uint8Array[]=[];
  let offset=0;
  const table=new Uint32Array(256);
  for(let n=0;n<256;n++){let c=n;for(let k=0;k<8;k++)c=c&1?0xedb88320^(c>>>1):c>>>1;table[n]=c>>>0;}
  const crc=(data:Uint8Array)=>{let c=0xffffffff;for(const b of data)c=table[(c^b)&255]^(c>>>8);return(c^0xffffffff)>>>0;};
  for(const {name,content} of entries){
    if(!/^[\w.-]{1,80}$/.test(name)||name==="."||name==="..")
      throw new Error("INVALID_PROJECT_PATH");
    const file=te.encode(content),fileName=te.encode(name);
    if(file.length>120_000)throw new Error("PROJECT_FILE_TOO_LARGE");
    const checksum=crc(file);
    const header=new Uint8Array(30+fileName.length);
    const h=new DataView(header.buffer);
    h.setUint32(0,0x04034b50,true);
    h.setUint16(4,20,true);h.setUint16(6,0x0800,true);
    h.setUint32(14,checksum,true);
    h.setUint32(18,file.length,true);h.setUint32(22,file.length,true);
    h.setUint16(26,fileName.length,true);header.set(fileName,30);
    parts.push(header,file);
    const directory=new Uint8Array(46+fileName.length);
    const d=new DataView(directory.buffer);
    d.setUint32(0,0x02014b50,true);
    d.setUint16(4,20,true);d.setUint16(6,20,true);
    d.setUint16(8,0x0800,true);
    d.setUint32(16,checksum,true);
    d.setUint32(20,file.length,true);d.setUint32(24,file.length,true);
    d.setUint16(28,fileName.length,true);
    d.setUint32(42,offset,true);
    directory.set(fileName,46);
    central.push(directory);
    offset+=header.length+file.length;
  }
  const dirSize=central.reduce((sum,p)=>sum+p.length,0);
  const end=new Uint8Array(22),e=new DataView(end.buffer);
  e.setUint32(0,0x06054b50,true);
  e.setUint16(8,entries.length,true);e.setUint16(10,entries.length,true);
  e.setUint32(12,dirSize,true);e.setUint32(16,offset,true);
  const result=new Uint8Array(offset+dirSize+end.length);
  let pos=0;
  for(const part of [...parts,...central,end]){result.set(part,pos);pos+=part.length;}
  return result;
}
export function createPortableExperimentZip(run:PortableExperiment):Uint8Array{
  if(!/^[0-9a-f-]{36}$/i.test(run.id)||!run.code.trim()||run.code.length>6000)
    throw new Error("INVALID_PROJECT_CONTENT");
  const passed=run.sandbox_ran&&run.sandbox_succeeded===true;
  const failed=run.sandbox_ran&&run.sandbox_succeeded===false;
  const outcome=passed?"PASSED: the executed process exited successfully.":
    failed?"FAILED: the tested code did not pass. Review the test output.":
    "NOT VERIFIED: no reliable successful execution was recorded.";
  const tick=String.fromCharCode(96);
  const readme=[
    "# Your AGENT Node.js program",
    "",
    "This is a standalone copy of the generated program, not a modification to the AGENT app.",
    "It was prepared in an isolated Work Run. It was NOT committed, merged, or deployed.",
    "",
    "## Task",
    run.task.slice(0,1500),
    "",
    "## Run it",
    "Requires Node.js 22 or compatible. From this folder: "+tick+"node program.js"+tick+".",
    "The generated program may contain built-in assertions which run with the program.",
    "No third-party packages were installed or verified in this experiment.",
    "If the code needs third-party modules, you must review its dependencies first.",
    "",
    "## Original plan",
    ...(run.steps||[]).slice(0,5).map((s,i)=>String(i+1)+". "+String(s).slice(0,180)),
    "",
    "## Test status",
    outcome,
    "A successful process exit is NOT a guarantee that all app functions are correct.",
    "See TEST-RESULTS.txt for the recorded commands and details.",
    "",
    "## Isolation",
    "AGENT codebase: unchanged. No files pushed to GitHub; no pull request or merge.",
    run.github_run_id?"GitHub Actions workflow run: "+run.github_run_id:"Runner: isolated local Sandbox or no runner."
  ].join("\n");
  const meta={
    name:"agent-generated-program",
    version:"0.0.1",
    private:true,
    description:"Independent Node.js experiment generated by AGENT",
    scripts:{start:"node program.js",test:"node program.js"}
  };
  const testLog=[
    "AGENT Work Run: "+run.id,
    "Status: "+run.status,
    "Result: "+outcome,
    "The following is recorded process output; it is not the model's internal reasoning.",
    "",
    String(run.execution_log||"No terminal output recorded.").slice(0,7600)
  ].join("\n");
  return zipStore([
    {name:"README.md",content:readme},
    {name:"program.js",content:run.code},
    {name:"package.json",content:JSON.stringify(meta,null,2)+"\n"},
    {name:"TEST-RESULTS.txt",content:testLog}
  ]);
}
